const $ = id => document.getElementById(id);
const send = (type, data = {}) => chrome.runtime.sendMessage({ type, ...data });
const checkId = new URLSearchParams(location.search).get('c');
const LABEL = { low: 'Low', medium: 'Medium', high: 'High' };
let verifiedPin = null; // Kept only in this parent review window, never saved in browser storage.

function expired(text) {
  verifiedPin = null;
  $('main').replaceChildren();
  const p = document.createElement('p'); p.className = 'done'; p.textContent = text;
  $('main').append(p);
}

$('pin').addEventListener('input', e => {
  e.target.value = e.target.value.replace(/\D/g, '');
  $('verify').disabled = e.target.value.length < 4;
  $('msg').textContent = '';
});
$('pin').addEventListener('keydown', e => {
  if (e.key === 'Enter' && !$('verify').disabled) verify();
});

async function verify() {
  const pin = $('pin').value;
  if (!/^\d{4,8}$/.test(pin)) return;
  $('verify').disabled = true;
  $('msg').textContent = 'Verifying parent PIN…';
  try {
    // The backend checks the PIN BEFORE it returns flagged text or coaching tips.
    const r = await send('coaching', { checkId, pin });
    if (r.error || r.unpaired || r.offline) {
      $('msg').textContent = r.error || 'Cannot reach the server. Try again.';
      $('pin').value = '';
      $('verify').disabled = true;
      $('pin').focus();
      return;
    }
    verifiedPin = pin;
    $('pin').value = '';
    $('title').textContent = r.title || '(untitled post)';
    $('badge').className = 'badge ' + r.bucket;
    $('badge').textContent = (LABEL[r.bucket] || 'Flagged') + ' toxicity';
    $('lvl').textContent = (LABEL[r.bucket] || 'flagged').toLowerCase() + '-toxicity thread';
    $('block').textContent = `Block ${LABEL[r.bucket] || 'This'} Toxicity for 30 Days`;
    $('bodyText').textContent = r.body || '';
    $('bodyText').hidden = !r.body;
    const comments = Array.isArray(r.comments) ? r.comments : [];
    $('commentSection').hidden = comments.length === 0;
    $('comments').replaceChildren(...comments.map(t => {
      const li = document.createElement('li'); li.textContent = t; return li;
    }));
    // Preserve the existing backend contract: three generated tips, one per step.
    const tips = Array.isArray(r.tips) ? r.tips : [];
    $('tipContext').textContent = tips[0] || 'Review the tone and context before making a decision.';
    $('tipAsk').textContent = tips[1] || 'What do you think about what you read here?';
    $('tipReflect').textContent = tips[2] || 'How can we tell whether online advice is fair or helpful?';
    $('src').textContent = r.source === 'gemini' ? 'Conversation suggestions generated by Gemini. They are not a clinical or moderation verdict.' : 'General conversation suggestions (Gemini unavailable).';
    $('summary').textContent = `${LABEL[r.bucket] || 'Flagged'} toxicity predicted from discussion signals. ${tips[0] || 'Review the original post and sampled comments for context.'}`;
    $('verifiedStatus').textContent = 'Verified';
    $('gate').hidden = true;
    $('details').hidden = false;
    $('threadDetails').open = false;
  } catch (e) {
    $('msg').textContent = 'Unable to verify. Try again.';
    $('verify').disabled = false;
  }
}

async function decide(decision) {
  if (!verifiedPin) return;
  $('view').disabled = $('block').disabled = true;
  let r;
  try {
    r = await send('decision', { checkId, pin: verifiedPin, decision });
  } catch (_) { r = { error: 'Unable to reach server.' }; }
  if (r.action) {
    expired(r.action === 'unlock' ? '✓ Unlocked for this thread.' : '✓ Blocked for 30 days. Your teen is back on the home feed.');
    setTimeout(() => window.close(), 1200);
    return;
  }
  $('decisionMsg').textContent = r.offline ? 'Cannot reach the server. Try again.' : (r.error || 'Something went wrong.');
  $('view').disabled = $('block').disabled = false;
  if (r.status === 403 || r.status === 429 || r.unpaired) {
    verifiedPin = null;
    $('details').hidden = true;
    $('gate').hidden = false;
    $('msg').textContent = $('decisionMsg').textContent;
    $('pin').focus();
  }
}
$('verify').onclick = verify;
$('view').onclick = () => decide('view');
$('block').onclick = () => decide('block');
$('pin').focus();

